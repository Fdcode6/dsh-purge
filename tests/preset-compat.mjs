import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { readPresetDefinition } from '../lib/redteam/preset-composition.js';
import { compatiblePresets, registerCompatiblePresets } from '../lib/redteam/preset-compat.js';
const original = readPresetDefinition('redteam', fileURLToPath(new URL('../presets/redteam/', import.meta.url)));

const before = JSON.stringify(original);
const presets = compatiblePresets(original);
assert.equal(presets.length, 2);
assert.equal(JSON.stringify(original), before);
const flatten = rows => rows.flatMap(row => [row, ...(row.group ? flatten(row.config) : [])]);
const leaf = flatten(presets[0].plugins);
assert(!leaf.some(row => /dsh-tool-subagent|dsh-tool-workflow|dsh-tool-ralph|dsh-workflow-/.test(row.name)));
assert(leaf.some(row => row.name === 'dsh-purge/redteam/tools'));
const parent = flatten(presets[1].plugins);
const spawn = parent.find(row => row.name === '@deepseek-ai/dsh-tool-subagent' && row.config.provider === 'spawn');
assert.equal(spawn.config.agentPreset, 'redteam-worker');
assert.equal(spawn.config.maxDepth, 1);
assert(!parent.some(row => row.name === '@deepseek-ai/dsh-tool-subagent' && 'toolFilter' in row.config));
const custom = structuredClone(original);
flatten(custom.plugins).find(row => row.name === '@deepseek-ai/dsh-tool-subagent' && row.config.provider === 'spawn').config.toolFilter.deny.push('terminal');
assert.throws(() => compatiblePresets(custom), /Unsupported custom/);
let registered = [], disposed = [];
const registry = { register: async p => { registered.push(p.id); return () => disposed.push(p.id); }, list: async () => registered.map(id => ({id})) };
const cleanup = await registerCompatiblePresets(registry, original);
assert.deepEqual(registered, ['redteam-worker','redteam']);
await cleanup(); await cleanup();
assert.deepEqual(disposed, ['redteam','redteam-worker']);
registered=[]; disposed=[];
registry.list = async () => registered.map(id => ({id, broken: id === 'redteam' ? 'test failure' : null}));
await assert.rejects(registerCompatiblePresets(registry, original), /test failure/);
assert.deepEqual(disposed, ['redteam','redteam-worker']);
console.log('PASS: real preset parsing, leaf restrictions, original preservation, custom-filter rejection, registration order and rollback');
